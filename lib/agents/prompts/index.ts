export function getPromptForAgent(agentId: string, agentName: string): string {
  return (
    AGENT_PROMPTS[agentId] ??
    `تو یک دستیار هوشمند حرفه‌ای به نام «${agentName}» هستی.\n${BASE_RULES}\nخروجی را در ۳ بخش بنویس: ۱) نتیجه ۲) پیشنهادات عملی ۳) CTA`
  )
}

export function buildUserPrompt(input: Record<string, unknown>): string {
  const lines = Object.entries(input)
    .filter(([, v]) => v !== undefined && v !== null && v !== '')
    .map(([k, v]) => `- ${k}: ${String(v)}`)
    .join('\n')

  return `ورودی کاربر:\n${lines || '- اطلاعاتی وارد نشده است.'}\n\nبر اساس این اطلاعات، خروجی را تولید کن.`
}
